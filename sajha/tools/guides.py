"""
SAJHA MCP Server — the tool tables of the Tool Reference Guides, generated from the tool configs.
Copyright All rights Reserved 2025-2030, Ashutosh Sinha, Email: ajsinha@gmail.com

    python -m sajha.tools guides [--folder NAME] [--check]

A guide under ``docs/tools/`` marks the region this rewrites; everything outside it stays hand-written:

    <!-- generated:tools folder=fred group=category -->
    ...generated...
    <!-- /generated:tools -->

Marker attributes: ``folder`` (required: the tool folder under the tools directory), ``group=category``
(one ``###`` table per ``metadata.category``; default one table), ``include`` and ``exclude``
(comma-separated globs of tool names; an ``exclude`` entry ``!glob`` keeps what it names). Columns: tool, title (when any tool has one), the first sentence of
the tool's own description, required parameters, optional parameters with their schema defaults,
annotations, and the key the tool needs (stated once above the table when every tool needs the same one).
A schema built in code (no ``inputSchema`` in the config) is read from the tool class; when a module the
config ``requires`` is not installed the region is left as it is and reported, never rewritten.

``--check`` writes nothing and exits 1 when a region is stale; tests/test_tool_guides.py runs it.
Design: docs/architecture/Tool Quality.md §12.5.
"""

from __future__ import annotations

import fnmatch
import json
import logging
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)

REPO = Path(__file__).resolve().parents[2]
GUIDES_DIR = REPO / 'docs' / 'tools'
BEGIN_RE = re.compile(r'<!--\s*generated:tools\s+(?P<attrs>[^>]*?)\s*-->')
END = '<!-- /generated:tools -->'
NOTE = ('<!-- Generated by `python -m sajha.tools guides` from the tool configs in {where}; edit the configs, '
        'not this table. -->')
MAX_OPTIONAL = 12
MAX_SENTENCE = 300
_ABBREV = ('e.g.', 'i.e.', 'vs.', 'etc.', 'St.', 'U.S.', 'Inc.', 'No.', 'approx.', 'Corp.', 'Ltd.', 'Co.', 'Jr.',
           'Mr.', 'Dr.', 'cf.')
_KEY_WORDS = ('key', 'secret', 'token', 'password')


class Unavailable(Exception):
    """The region cannot be generated in this environment (a required module is missing)."""


@dataclass
class Region:
    folder: str
    group: str = ''
    include: List[str] = field(default_factory=list)
    exclude: List[str] = field(default_factory=list)


def parse_attrs(text: str) -> Region:
    attrs = dict(re.findall(r'([a-z_]+)=("[^"]*"|\S+)', text or ''))
    attrs = {k: v.strip('"') for k, v in attrs.items()}
    folder = attrs.get('folder', '')
    if not folder:
        raise ValueError('a generated:tools marker needs folder=<name>')
    def split(v: str) -> List[str]:
        return [x.strip() for x in v.split(',') if x.strip()]
    return Region(folder=folder, group=attrs.get('group', ''), include=split(attrs.get('include', '')),
                  exclude=split(attrs.get('exclude', '')))


# ── reading the configs ─────────────────────────────────────────────────

def _storage():
    from sajha.core.storage import get_storage
    return get_storage()


def _prefix() -> str:
    from sajha.tools.tool_files import default_prefix
    return default_prefix()


def folder_configs(folder: str) -> List[Dict[str, Any]]:
    """The raw (unsubstituted) configs in one tool folder, by tool name."""
    st, prefix = _storage(), _prefix()
    out = []
    for rel in st.list_files(f'{prefix}/{folder}', '*.json'):
        rel = rel.replace('\\', '/')
        if Path(rel).name.startswith('.') or rel.count('/') != prefix.count('/') + 2:
            continue
        try:
            cfg = st.read_json(rel)
        except Exception as e:
            logger.warning(f'{rel}: {e}')
            continue
        if isinstance(cfg, dict):
            cfg.setdefault('name', Path(rel).stem)
            out.append(cfg)
    return sorted(out, key=lambda c: str(c.get('name')))


def effective_schema(cfg: Dict[str, Any]) -> Dict[str, Any]:
    """The input schema clients see: the config's, else the one the tool class builds."""
    schema = cfg.get('inputSchema')
    if isinstance(schema, dict) and schema.get('properties'):
        return schema
    impl = cfg.get('implementation')
    if not isinstance(impl, str) or '.' not in impl:
        return schema if isinstance(schema, dict) else {}
    from sajha.tools.tools_registry import missing_requirements
    missing = missing_requirements(cfg)
    if missing:
        raise Unavailable(f'{cfg.get("name")} requires {", ".join(missing)}, which is not installed')
    import importlib
    module_path, class_name = impl.rsplit('.', 1)
    tool = getattr(importlib.import_module(module_path), class_name)(json.loads(json.dumps(cfg)))
    built = tool.input_schema
    return built if isinstance(built, dict) else {}


# ── formatting ──────────────────────────────────────────────────────────

def _cell(text: Any) -> str:
    s = re.sub(r'\s+', ' ', str(text if text is not None else '')).strip()
    return s.replace('|', '\\|')


def first_sentence(text: str) -> str:
    """The first sentence of a description (at most MAX_SENTENCE characters, cut at a word)."""
    s = re.sub(r'\s+', ' ', (text or '').split('\n', 1)[0]).strip()
    i = 0
    while True:
        m = re.search(r'[.!?](?=\s|$)', s[i:])
        if not m:
            break
        end = i + m.end()
        if any(s[:end].endswith(a) for a in _ABBREV) and end < len(s):
            i = end
            continue
        s = s[:end]
        break
    if len(s) > MAX_SENTENCE:
        s = s[:MAX_SENTENCE].rsplit(' ', 1)[0].rstrip(',;:') + ' …'
    return s


def _value(v: Any) -> str:
    return f'`{v}`' if isinstance(v, str) else f'`{json.dumps(v)}`'


def parameters(schema: Dict[str, Any]) -> Tuple[str, str]:
    """(required, optional with defaults) of an input schema."""
    props = schema.get('properties') if isinstance(schema, dict) else None
    if not isinstance(props, dict) or not props:
        return '—', '—'
    required = [p for p in (schema.get('required') or []) if p in props]
    req = ', '.join(f'`{p}`' for p in required) or '—'
    opt = []
    for name, spec in props.items():
        if name in required:
            continue
        if isinstance(spec, dict) and 'default' in spec:
            opt.append(f'`{name}` ({_value(spec["default"])})')
        else:
            opt.append(f'`{name}`')
    if len(opt) > MAX_OPTIONAL:
        opt = opt[:MAX_OPTIONAL] + [f'and {len(opt) - MAX_OPTIONAL} more']
    return req, ', '.join(opt) or '—'


def annotations(cfg: Dict[str, Any]) -> str:
    a = cfg.get('annotations') if isinstance(cfg.get('annotations'), dict) else {}
    out = []
    if a.get('readOnlyHint') is True:
        out.append('read-only')
    if a.get('destructiveHint') is True:
        out.append('destructive')
    if a.get('idempotentHint') is True:
        out.append('idempotent')
    if a.get('openWorldHint') is True:
        out.append('open-world')
    elif a.get('openWorldHint') is False:
        out.append('closed-world')
    if cfg.get('enabled') is False:
        out.append('disabled')
    return ', '.join(out) or '—'


_yaml_cache: Optional[Dict[str, Any]] = None


def _app_yaml() -> Dict[str, Any]:
    global _yaml_cache
    if _yaml_cache is None:
        try:
            import yaml
            _yaml_cache = yaml.safe_load((REPO / 'config' / 'application.yml').read_text()) or {}
        except Exception:
            _yaml_cache = {}
    return _yaml_cache


def _env_of(dotted: str) -> str:
    """The environment variable application.yml binds a dotted key to ('' when none)."""
    node: Any = _app_yaml()
    for part in dotted.split('.'):
        if not isinstance(node, dict) or part not in node:
            return ''
        node = node[part]
    m = re.fullmatch(r'\$\{([A-Z][A-Z0-9_]*)(?::[^}]*)?\}', str(node or '').strip())
    return m.group(1) if m else ''


def keys(cfg: Dict[str, Any]) -> str:
    """The keys a tool's config reads (``${...}`` references naming a key, secret, token or password)."""
    text = json.dumps({k: v for k, v in cfg.items() if k not in ('inputSchema', 'outputSchema', 'description')})
    out = []
    for ref in re.findall(r'\$\{([^}:]+)(?::[^}]*)?\}', text):
        last = ref.split('.')[-1].lower()
        if not any(w in last for w in _KEY_WORDS):
            continue
        if re.fullmatch(r'[A-Z][A-Z0-9_]*', ref):
            label = f'`{ref}`'
        else:
            env = _env_of(ref)
            label = f'`{env}` (config `{ref}`)' if env else f'config `{ref}`'
        if label not in out:
            out.append(label)
    return ', '.join(out)


def _selected(cfg: Dict[str, Any], region: Region) -> bool:
    """In ``include`` (when given) and not in ``exclude``; an exclude entry ``!glob`` keeps what it names."""
    name = str(cfg.get('name'))
    if region.include and not any(fnmatch.fnmatchcase(name, g) for g in region.include):
        return False
    if any(g.startswith('!') and fnmatch.fnmatchcase(name, g[1:]) for g in region.exclude):
        return True
    return not any(fnmatch.fnmatchcase(name, g) for g in region.exclude if not g.startswith('!'))


def render(region: Region) -> str:
    """The generated body of one region (between the markers, without them)."""
    configs = [c for c in folder_configs(region.folder) if _selected(c, region)]
    if not configs:
        raise ValueError(f'no tool configs in folder {region.folder!r} match this region')
    rows = []
    for cfg in configs:
        req, opt = parameters(effective_schema(cfg))
        rows.append({'cfg': cfg, 'name': str(cfg['name']), 'title': _cell(cfg.get('title') or ''),
                     'desc': _cell(first_sentence(cfg.get('description') or '')), 'req': req, 'opt': opt,
                     'ann': annotations(cfg), 'key': keys(cfg),
                     'cat': _cell(((cfg.get('metadata') or {}).get('category')) or 'Other')})
    with_title = any(r['title'] for r in rows)
    key_set = {r['key'] for r in rows}
    shared_key = key_set.pop() if len(key_set) == 1 else None
    head = ['Tool'] + (['Title'] if with_title else []) + ['Description', 'Required', 'Optional (schema default)',
                                                           'Annotations']
    if shared_key is None:
        head.append('Key')

    def table(items) -> List[str]:
        out = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
        for r in items:
            cells = [f'`{r["name"]}`'] + ([r['title'] or '—'] if with_title else []) + \
                    [r['desc'] or '—', r['req'], r['opt'], r['ann']]
            if shared_key is None:
                cells.append(r['key'] or '—')
            out.append('| ' + ' | '.join(cells) + ' |')
        return out

    lines = [NOTE.format(where=f'`{_prefix()}/{region.folder}/`'), '']
    if shared_key:
        lines += [f'Every tool below needs the key {shared_key}.', '']
    if region.group == 'category':
        cats: Dict[str, list] = {}
        for r in rows:
            cats.setdefault(r['cat'], []).append(r)
        for cat in sorted(cats, key=str.lower):
            lines += [f'### {cat}', ''] + table(cats[cat]) + ['']
    else:
        lines += table(rows) + ['']
    return '\n'.join(lines)


# ── rewriting guides ────────────────────────────────────────────────────

@dataclass
class Result:
    path: Path
    folder: str
    status: str            # 'ok' | 'stale' | 'written' | 'unavailable' | 'error'
    detail: str = ''


def process(text: str, path: Path, only_folder: Optional[str] = None) -> Tuple[str, List[Result]]:
    """(the guide with every marked region regenerated, a result per region)."""
    out, results, pos = [], [], 0
    for m in BEGIN_RE.finditer(text):
        if m.start() < pos:
            continue
        end = text.find(END, m.end())
        if end < 0:
            results.append(Result(path, '?', 'error', f'a marker at offset {m.start()} has no {END}'))
            break
        try:
            region = parse_attrs(m.group('attrs'))
        except ValueError as e:
            results.append(Result(path, '?', 'error', str(e)))
            out.append(text[pos:end])           # the region as it is, marker included
            pos = end
            continue
        out.append(text[pos:m.end()])
        current = text[m.end():end]
        if only_folder and region.folder != only_folder:
            out.append(current)
        else:
            try:
                body = '\n' + render(region) + '\n'
                results.append(Result(path, region.folder, 'ok' if body == current else 'stale'))
                out.append(body)
            except Unavailable as e:
                results.append(Result(path, region.folder, 'unavailable', str(e)))
                out.append(current)
            except Exception as e:
                results.append(Result(path, region.folder, 'error', str(e)))
                out.append(current)
        pos = end
    out.append(text[pos:])
    return ''.join(out), results


def guide_paths(root: Optional[Path] = None) -> List[Path]:
    return sorted(p for p in (root or GUIDES_DIR).rglob('*.md') if p.is_file())


def run(check: bool = False, folder: Optional[str] = None, root: Optional[Path] = None) -> List[Result]:
    results: List[Result] = []
    for path in guide_paths(root):
        text = path.read_text(encoding='utf-8')
        if 'generated:tools' not in text:
            continue
        new, res = process(text, path, folder)
        if not check and new != text:
            path.write_text(new, encoding='utf-8')
            for r in res:
                if r.status == 'stale':
                    r.status = 'written'
        results += res
    return results


def main(check: bool = False, folder: Optional[str] = None, out=None) -> int:
    import sys
    out = out or sys.stdout
    results = run(check=check, folder=folder)
    bad = 0
    for r in results:
        rel = r.path.relative_to(REPO) if r.path.is_relative_to(REPO) else r.path
        if r.status in ('stale', 'error'):
            bad += 1
        if r.status != 'ok' or not check:
            print(f'{r.status:<11} {rel} [{r.folder}]' + (f': {r.detail}' if r.detail else ''), file=out)
    if not results:
        print('no generated:tools regions found', file=out)
    if check and bad:
        print(f'{bad} region(s) stale or broken: run python -m sajha.tools guides', file=out)
    return 1 if (check and bad) or any(r.status == 'error' for r in results) else 0
