# qlrisk fields build_trades fills in when they are left out
DEFAULTED = ("trade_id", "trade_date", "effective_date", "counterparty_id", "currency")
CALL_FIELDS = ("market_data", "reporting_currency", "include_cash_flows")
# qlrisk fields that must come in this order when both are given: (earlier, later, may be equal)
ORDER = (("attachment", "detachment", False), ("option_expiry", "swap_effective", True), ("swap_effective", "swap_maturity", False),
         ("near_date", "far_date", False), ("fixing_date", "settlement_date", True),
         ("settlement_date", "maturity_date", False), ("effective_date", "maturity_date", False))
_TENOR = re.compile(r"^\s*(\d+(?:\.\d+)?)\s*([dwmy])\s*$", re.I)


def slug(product: str) -> str:
    """InterestRateSwap -> interest_rate_swap, FXOption -> fx_option, MTMCrossCurrencySwap -> mtm_cross_currency_swap."""
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", product).lower()
    return re.sub(r"_+", "_", re.sub(r"[^a-z0-9_]", "_", s)).strip("_")


def tool_name(product: str) -> str:
    return f"qlrisk_price_{slug(product)}"


# ── tenors ──────────────────────────────────────────────────────────


def _add_months(d: date, months: int) -> date:
    y, m = divmod(d.month - 1 + months, 12)
    year, month = d.year + y, m + 1
    return date(year, month, min(d.day, calendar.monthrange(year, month)[1]))


def tenor_or_date(value: Any, valuation: date, what: str) -> date:
    """'3Y', '18M', '6W', '10D' (from the valuation date; '1.5Y' = 18 months) or an ISO date."""
    text = str(value).strip()
    m = _TENOR.match(text)
    if m:
        n, unit = float(m.group(1)), m.group(2).upper()
        if unit == "Y":
            return _add_months(valuation, round(n * 12))
        if n != int(n):
            raise InvalidInput(f"{what}: {text!r}: use a whole number of {dict(M='months', W='weeks', D='days')[unit]}")
        if unit == "M":
            return _add_months(valuation, int(n))
        return valuation + timedelta(days=int(n) * (7 if unit == "W" else 1))
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", text):
        return parse_date(text, what)
    raise InvalidInput(f"{what}: {text!r} is neither a tenor like 3Y, 18M, 6W or 10D nor a date YYYY-MM-DD")


# ── the exposed fields ──────────────────────────────────────────────


@dataclass(frozen=True)
class Exposed:
    qname: str                       # qlrisk's field
    name: str                        # the tool's input name
    schema: Dict[str, Any]
    spec: Any                        # generate.F
    advanced: bool
    required: bool
    labels: Optional[Dict[str, Any]] = None


def _qlrisk_fields(product: str) -> List[Tuple[str, Dict[str, Any], bool]]:
    spec = I.product_spec(product)
    out = []
    for name, schema in {**spec["parameters"], **spec["terms"]}.items():
        if name in CALL_FIELDS or name == "advanced":
            raise ValueError(f"{product}: field {name!r} clashes with a call field")
        out.append((name, dict(schema), name in spec["required"] and name not in DEFAULTED))
    return out


def _description(f, qschema: Dict[str, Any], in_table: bool) -> str:
    if f.desc:
        return f.desc
    if qschema.get("description"):
        return qschema["description"].replace("default computed by qlrisk:", "Default computed by qlrisk:")
    if not in_table:
        t = qschema.get("type")
        numeric = t == "number" or (isinstance(t, list) and "number" in t and "string" not in t)
        return ("qlrisk term, passed as is in qlrisk's own units (rates as decimals: 0.03 = 3%)." if numeric
                else "qlrisk term, passed as is.")
    return ""


def _exposed(product: str, pricer: str, qname: str, qschema: Dict[str, Any], qrequired: bool) -> Optional[Exposed]:
    from ..generate import CODE_FREQ, FIELDS, NUM_FREQ, _NO, field_spec, notional_spec
    f = field_spec(product, pricer, qname)
    if f.hidden:
        return None
    name, title = f.name or qname, f.title or qname.replace("_", " ").capitalize()
    desc = _description(f, qschema, qname in FIELDS or f.desc != "")
    qdefault = qschema.get("default", _NO)
    labels = f.labels
    if f.freq:
        codes = qschema.get("enum")
        labels = {k: v for k, v in CODE_FREQ.items() if v in codes} if codes else dict(NUM_FREQ)
    if qname == "notional":
        name, title, default, desc = notional_spec(product, pricer)
        s: Dict[str, Any] = {"type": "number", "exclusiveMinimum": 0, "default": default}
    elif f.nested is not None:                     # a qlrisk object whose fields have their own units
        from ..units import field_schema
        s = {k: v for k, v in field_schema(f, qschema).items() if k not in ("title", "description")}
    elif labels:
        s = {"type": "string", "enum": list(labels)}
        if f.default is not _NO:
            s["default"] = f.default
        elif qdefault is not _NO:
            back = [k for k, v in labels.items() if v == qdefault]
            if back:
                s["default"] = back[0]
    elif f.tenor:
        s = {"type": "string"}
        if f.default is not _NO:
            s["default"] = f.default
    else:
        s = {k: v for k, v in qschema.items() if k != "description"}
        if f.type:
            s["type"] = f.type
        if f.scale != 1.0:
            s["type"] = "number"
            s.pop("default", None)
            if isinstance(qdefault, (int, float)) and not isinstance(qdefault, bool):
                s["default"] = round(qdefault / f.scale, 10)
        if f.default is not _NO:
            s["default"] = f.default
        if f.minimum is not None:
            s["minimum"] = f.minimum
        if f.maximum is not None:
            s["maximum"] = f.maximum
        if f.positive:
            s["exclusiveMinimum"] = 0
    if isinstance(s.get("default"), float) and s["default"] == int(s["default"]):
        s["default"] = int(s["default"])
    s["title"] = title
    if desc:
        s["description"] = desc
    if f.required:
        s.pop("default", None)
    if f.tenor and f.example is not _NO:
        s["examples"] = [f.example, "2031-06-15"] if f.future else [f.example]
    elif f.example is not _NO and "enum" not in s and qname != "notional":
        s["examples"] = [f.example]
    required = f.required if f.required is not None else (qrequired and "default" not in s)
    return Exposed(qname=qname, name=name, schema=s, spec=f, advanced=f.advanced and not required,
                   required=bool(required), labels=labels)


@lru_cache(maxsize=None)
def exposed_fields(product: str) -> Tuple[Exposed, ...]:
    """The product's inputs, in form order: maturity, notional, required terms, the rest, currency; then advanced."""
    pricer = I.product_spec(product)["pricer"]
    fields = [e for e in (_exposed(product, pricer, *q) for q in _qlrisk_fields(product)) if e is not None]
    names = [e.name for e in fields]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        raise ValueError(f"{product}: two qlrisk fields map to {sorted(dupes)}")

    def rank(e: Exposed):
        return (e.advanced, 0 if e.name == "maturity" else 1 if e.qname in ("notional", "base_notional") else
                2 if e.required else 4 if e.qname == "currency" else 3)
    return tuple(sorted(fields, key=rank))


def advanced_schema(product: str) -> Dict[str, Any]:
    props = {e.name: e.schema for e in exposed_fields(product) if e.advanced}
    props["market_data"] = {**market_data_schema(), "title": "Market data"}
    props["reporting_currency"] = {**currency_prop(), "title": "Reporting currency"}
    props["include_cash_flows"] = {"type": "boolean", "default": False, "title": "Include cash flows"}
    out = obj(props)
    out["title"] = "Advanced (optional)"
    out["description"] = ("Optional: trade ids and dates, issuer, position direction, market data (default qlrisk's "
                          "sample snapshot valued today), reporting currency, cash flows.")
    return out


@lru_cache(maxsize=None)
def product_tool(product: str, limits) -> ToolDef:
    """The ToolDef of one product's pricing tool (schema built from the installed qlrisk and the field table)."""
    if product not in I.product_classes():
        raise ValueError(f"{product!r} is not a qlrisk product")
    spec = I.product_spec(product)
    fields = [e for e in exposed_fields(product) if not e.advanced]
    props = {e.name: e.schema for e in fields}
    props["advanced"] = advanced_schema(product)
    return ToolDef(name=tool_name(product), title=f"Price a {product}",
                   description=f"Price one qlrisk {product}: {spec['description']}",
                   input_schema=obj(props, [e.name for e in fields if e.required]),
                   handler=lambda args, ctx: price_one(product, args, ctx))


# ── arguments -> qlrisk trade ───────────────────────────────────────


def _check(e: Exposed, value: Any, valuation: date, warnings: List[str]) -> Any:
    """Validate one input (exposed units) and return qlrisk's value."""
    f, what = e.spec, e.name
    if f.nested is not None:
        from ..units import convert
        return convert(f, e.schema, value, what, warnings)
    if e.labels:
        if value not in e.labels:
            raise InvalidInput(f"{what}: {value!r} is not one of {list(e.labels)}")
        return e.labels[value]
    if f.tenor:
        d = tenor_or_date(value, valuation, what)
        if f.future and d <= valuation:
            raise InvalidInput(f"{what}: {value!r} is {d.isoformat()}, not after the valuation date {valuation.isoformat()}")
        return d.isoformat()
    s = e.schema
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        unit = f" {f.unit}" if f.unit else ""
        lo, hi = s.get("minimum"), s.get("maximum")
        if (lo is not None and value < lo) or (hi is not None and value > hi):
            hint = " (rates are in percent: 3 means 3%)" if f.unit == "percent" else \
                " (spreads are in basis points: 25 means 0.25%)" if f.unit == "basis points" else ""
            raise InvalidInput(f"{what}: {value} is outside {lo} to {hi}{unit}{hint}")
        if "exclusiveMinimum" in s and value <= s["exclusiveMinimum"]:
            raise InvalidInput(f"{what}: must be greater than {s['exclusiveMinimum']}, got {value}")
        if f.warn and not (f.warn[0] <= value <= f.warn[1]):
            warnings.append(f"{what} = {value}{unit} is outside the usual {f.warn[0]} to {f.warn[1]}{unit}; check it")
        if f.unit == "percent" and 0 < abs(value) < 0.2:
            warnings.append(f"{what} = {value} means {value}%; for {value * 100:g}% send {value * 100:g}")
        if f.scale != 1.0:
            return round(value * f.scale, 12)
    return value


def to_trade(product: str, args: Dict[str, Any], valuation: date, warnings: List[str]) -> Dict[str, Any]:
    """The qlrisk trade dict (qlrisk's field names and units) for the tool's arguments."""
    adv = args.get("advanced") or {}
    trade: Dict[str, Any] = {}
    for e in exposed_fields(product):
        src = adv if e.advanced else args
        if e.name in src and src[e.name] is not None:
            value = src[e.name]
        elif "default" in e.schema:
            value = e.schema["default"]
        elif e.required:
            raise InvalidInput(f"{e.name}: required ({e.schema.get('title', e.name)})")
        else:
            continue
        trade[e.qname] = _check(e, value, valuation, warnings)
    by_q = {e.qname: e.name for e in exposed_fields(product)}
    for a, b, equal_ok in ORDER:
        if a in trade and b in trade:
            x, y = trade[a], trade[b]
            if x > y or (x == y and not equal_ok):
                raise InvalidInput(f"{by_q[b]}: must be after {by_q[a]} ({x} vs {y})")
    return trade


# ── trades in a book (qlrisk_price_trades, VaR, SA-CCR ...) ─────────

TRADE_EXTRAS = {"netting_set_id": {"type": "string", "title": "Netting set id",
                                   "description": "Defaults to the counterparty id."},
                "csa_id": {"type": "string", "title": "CSA id"}}


@lru_cache(maxsize=None)
def trade_item_schema(product: str) -> Dict[str, Any]:
    """One trade of a book: "product" plus the product tool's inputs, flat (its trade-level advanced fields too)."""
    fields = exposed_fields(product)
    props: Dict[str, Any] = {"product": {"const": product}}
    props.update({e.name: e.schema for e in fields})
    props.update(TRADE_EXTRAS)
    return obj(props, ["product"] + [e.name for e in fields if e.required])


def resolve_product(name: Any) -> Optional[str]:
    classes = I.product_classes()
    if name in classes:
        return name
    lowered = {c.lower(): c for c in classes}
    by_type = {I.product_spec(c)["product_type"]: c for c in classes}
    return lowered.get(str(name).lower()) or by_type.get(str(name).lower())


def human_trade(raw: Dict[str, Any], where: str, valuation: date, warnings: List[str]) -> Dict[str, Any]:
    """A book trade in the tools' units -> the qlrisk trade dict (qlrisk's names and units)."""
    import jsonschema
    if not isinstance(raw, dict) or "product" not in raw:
        raise InvalidInput(f"{where}: each trade is an object with 'product' (one of qlrisk_catalog's products) and "
                           "the inputs of that product's qlrisk_price_<product> tool")
    product = resolve_product(raw["product"])
    if product is None:
        raise InvalidInput(f"{where}.product {raw['product']!r} is not a qlrisk product; call qlrisk_catalog with topic 'products'")
    item = {**raw, "product": product}
    errors = sorted(jsonschema.Draft202012Validator(trade_item_schema(product)).iter_errors(item),
                    key=lambda e: list(e.absolute_path))
    if errors:
        err = errors[0]
        path = ".".join(str(x) for x in err.absolute_path)
        hint = ""
        if err.validator == "additionalProperties":
            hint = (f"; {product} takes {sorted(n for n in trade_item_schema(product)['properties'] if n != 'product')}"
                    " (rates in percent, spreads in basis points, maturity as a tenor like 5Y or a date)")
        raise InvalidInput(f"{where} ({product}){'.' + path if path else ''}: {err.message}{hint}")
    adv_names = {e.name for e in exposed_fields(product) if e.advanced}
    args = {k: v for k, v in item.items() if k not in adv_names and k not in TRADE_EXTRAS and k != "product"}
    args["advanced"] = {k: v for k, v in item.items() if k in adv_names}
    try:
        trade = to_trade(product, args, valuation, warnings)
    except InvalidInput as exc:
        raise InvalidInput(f"{where} ({product}).{exc}") from None
    trade.update({k: item[k] for k in TRADE_EXTRAS if k in item})
    return {"product": product, **trade}


def valuation_date(args: Dict[str, Any]) -> date:
    md = (args.get("advanced") or {}).get("market_data") or {}
    return parse_date(md["valuation_date"], "advanced.market_data.valuation_date") if md.get("valuation_date") else date.today()


def price_one(product: str, args: Dict[str, Any], ctx: Ctx):
    from .pricing import _price
    adv = args.get("advanced") or {}
    trade = to_trade(product, args, valuation_date(args), ctx.warnings)
    out, _ = _price({"trades": [{"product": product, **trade}], "_qlrisk_units": True, "market_data": adv.get("market_data"),
                     "reporting_currency": adv.get("reporting_currency", "USD"),
                     "include_cash_flows": adv.get("include_cash_flows", False)}, ctx)
    if out["errors"]:
        raise RuntimeError(f"pricing failed: {out['errors'][0]['error']}")
    row = out["trades"][0]
    ccy = out["reporting_currency"]
    result = {"valuation_date": out["valuation_date"], "reporting_currency": ccy, **row,
              "qlrisk_terms": to_jsonable(trade)}
    summary = f"{product} on {out['valuation_date']}: NPV {rounded(row['npv'])} {row['currency']}"
    if row["currency"] != ccy:
        summary += f" ({rounded(row['npv_reporting'])} {ccy})"
    return result, summary
