"""
Per-product pricing tools: qlrisk_price_<product>, one per qlrisk product class.

Each tool's input schema holds only its product's economic terms, under human names and units: rates in
percent (coupon_pct 3 = 3%), spreads in basis points, a maturity as a tenor (3Y, 18M, 6W, 10D) or a date,
the notional under its product's name (face_value for bonds) with a default, payment frequencies as words.
Trade ids and dates, issuer, position direction, market_data, reporting_currency and include_cash_flows sit
in one optional ``advanced`` object. The field table (names, units, conversions, bounds, defaults) is
FIELDS / OVERRIDES / NOTIONAL in generate.py; this module builds the schemas from it and from qlrisk's
product spec, converts the arguments to qlrisk's own units (decimals: 0.03 is 3%) and prices the trade
through the same code as qlrisk_price_trades. The tool configs are generated by generate.py.
"""

