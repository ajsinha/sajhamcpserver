"""
Per-product pricing tools: qlrisk_price_<product>, one per qlrisk product class.

Each tool's input schema holds only its product's fields (constructor parameters and the keyword terms
its pricer reads, from introspect.product_spec) plus market_data, reporting_currency and
include_cash_flows, as qlrisk_price_trades takes them. The handler prices one trade through the same
code as qlrisk_price_trades. The tool configs are generated by sajha/tools/impl/qlrisk/generate.py.
"""

from __future__ import annotations

import re
from functools import lru_cache
from typing import Any, Dict, List

from .. import introspect as I
from ..inputs import market_data_schema
from ..jsonable import rounded
from . import Ctx, ToolDef, currency_prop, obj

# fields build_trades fills in when they are left out (so they are optional here)
DEFAULTED = ("trade_id", "trade_date", "effective_date", "counterparty_id", "currency", "maturity_date")
CALL_FIELDS = ("market_data", "reporting_currency", "include_cash_flows")


def slug(product: str) -> str:
    """InterestRateSwap -> interest_rate_swap, FXOption -> fx_option, MTMCrossCurrencySwap -> mtm_cross_currency_swap."""
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", product).lower()
    return re.sub(r"_+", "_", re.sub(r"[^a-z0-9_]", "_", s)).strip("_")


def tool_name(product: str) -> str:
    return f"qlrisk_price_{slug(product)}"


def required_fields(product: str) -> List[str]:
    return [r for r in I.product_spec(product)["required"] if r not in DEFAULTED]


def trade_properties(product: str) -> Dict[str, Any]:
    spec = I.product_spec(product)
    props: Dict[str, Any] = {}
    for name, schema in {**spec["parameters"], **spec["terms"]}.items():
        if name in CALL_FIELDS:
            raise ValueError(f"{product}: field {name!r} clashes with a call field")
        props[name] = dict(schema)
    if "maturity_date" in spec["parameters"]:
        props["tenor_years"] = {"type": "number", "description": "Instead of maturity_date: maturity = valuation date + tenor."}
    if "trade_id" in props:
        props["trade_id"].setdefault("description", f"Defaults to {product}-1.")
    if "currency" in props:
        props["currency"].setdefault("default", "USD")
    if "counterparty_id" in props:
        props["counterparty_id"].setdefault("default", "CP-1")
    for d in ("trade_date", "effective_date"):
        if d in props:
            props[d].setdefault("description", "Defaults to the valuation date.")
    return props


@lru_cache(maxsize=None)
def product_tool(product: str, limits) -> ToolDef:
    """The ToolDef of one product's pricing tool (schema built from the installed qlrisk)."""
    if product not in I.product_classes():
        raise ValueError(f"{product!r} is not a qlrisk product")
    spec = I.product_spec(product)
    props = {**trade_properties(product), "market_data": market_data_schema(),
             "reporting_currency": currency_prop(),
             "include_cash_flows": {"type": "boolean", "default": False}}
    return ToolDef(name=tool_name(product), title=f"Price a {product}",
                   description=f"Price one qlrisk {product}: {spec['description']}",
                   input_schema=obj(props, required_fields(product)),
                   handler=lambda args, ctx: price_one(product, args, ctx))


def price_one(product: str, args: Dict[str, Any], ctx: Ctx):
    from .pricing import _price
    trade = {k: v for k, v in args.items() if k not in CALL_FIELDS}
    out, _ = _price({"trades": [{"product": product, **trade}], "market_data": args.get("market_data"),
                     "reporting_currency": args.get("reporting_currency", "USD"),
                     "include_cash_flows": args.get("include_cash_flows", False)}, ctx)
    if out["errors"]:
        raise RuntimeError(f"pricing failed: {out['errors'][0]['error']}")
    row = out["trades"][0]
    ccy = out["reporting_currency"]
    result = {"valuation_date": out["valuation_date"], "reporting_currency": ccy, **row}
    summary = f"{product} {row['trade_id']} on {out['valuation_date']}: NPV {rounded(row['npv'])} {row['currency']}"
    if row["currency"] != ccy:
        summary += f" ({rounded(row['npv_reporting'])} {ccy})"
    return result, summary
